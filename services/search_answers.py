def _health_search_question_answer(query, lang, search_result=None):
    """Answer the user's *full* health-search question, preserving modifiers.

    The structured glossary result is still returned below for sources and
    topic details; this short answer prevents a natural-language question from
    being reduced to a single symptom keyword.
    """
    q = " ".join(str(query or "").split())[:600]
    if not q:
        return ""
    if isinstance(search_result, dict) and search_result.get("curated_answer"):
        return search_result["direct_answer"]
    # Relationship results always win over standalone symptom handlers.
    if isinstance(search_result, dict) and search_result.get("relation_query"):
        relation_text = str(search_result.get("what") or "").strip()
        if relation_text:
            return _strip_search_answer_heading(_assistant_compact_response(relation_text, lang, "search"), lang)

    contextual = _assistant_contextual_health_answer(q, lang)
    if contextual:
        return _strip_search_answer_heading(_assistant_compact_response(contextual, lang, "search"), lang)

    low = q.lower()
    ar = lang != "en"
    # Treat *every* non-empty health search as a full query. A one- or two-word
    # entry means "explain this health topic" rather than "pick a fuzzy card".

    # First answer common question intents directly from the structured search
    # result.  This keeps the search useful even when no external model is used.
    if isinstance(search_result, dict):
        causes = [str(x).strip() for x in (search_result.get("causes") or []) if str(x).strip()][:5]
        worry = str(search_result.get("worry") or "").strip()
        doctor = str(search_result.get("doctor") or "").strip()
        what = str(search_result.get("what") or "").strip()
        intent = str(search_result.get("search_intent_v4") or "").strip()
        if (intent == "causes" or (ar and any(x in low for x in ("ليش", "لماذا", "ما سبب", "وش سبب", "ايش سبب")))) and causes:
            return (("من الأسباب المحتملة المرتبطة بسؤالك: " + "، ".join(causes) + ". السبب الدقيق يعتمد على السياق ولا يمكن تأكيده من البحث وحده.") if ar else
                    ("Possible causes related to your question include: " + ", ".join(causes) + ". The exact cause depends on context and cannot be confirmed by search alone."))
        if intent == "urgency" or (ar and any(x in low for x in ("متى أراجع", "متى اروح", "متى أروح", "متى يحتاج", "هل خطير"))) or ((not ar) and any(x in low for x in ("when should", "when do i", "when to see", "is it serious"))):
            detail = worry or doctor
            if detail:
                return detail
        if intent == "care" or (ar and any(x in low for x in ("وش اسوي", "وش أسوي", "ماذا أفعل", "ايش اسوي", "كيف اتصرف"))) or ((not ar) and any(x in low for x in ("what should i do", "what can i do", "how should i"))):
            detail = doctor or what
            if detail:
                return detail
        if intent == "normality" or (ar and any(x in low for x in ("هل طبيعي", "طبيعي؟", "هل هذا طبيعي"))) or ((not ar) and any(x in low for x in ("is this normal", "is it normal"))):
            if what:
                return what + ((" راجع مختصًا إذا استمر العرض أو ساء." if ar else " Seek medical review if it persists or worsens."))
        if intent == "meaning" and what:
            return what

    # V202: if the local structured knowledge already answers the query, keep
    # the wording stable across repeated searches. The external model is used
    # only for genuine content gaps / query-only cases.
    if isinstance(search_result, dict) and not search_result.get("query_only"):
        what = str(search_result.get("what") or "").strip()
        self_care = str(search_result.get("self_care") or "").strip()
        if what:
            stable = what
            if self_care:
                stable += ((" ما يمكنك فعله الآن: " if ar else " What you can do now: ") + self_care)
            return _strip_search_answer_heading(_assistant_compact_response(stable, lang, "search"), lang)
        topics = [t for t in (search_result.get("matched_topics") or []) if isinstance(t, dict)]
        if topics:
            names = [str(t.get("title") or "").strip() for t in topics[:3] if str(t.get("title") or "").strip()]
            if names:
                return (("يعرض البحث المعلومات الموثقة المرتبطة بـ " + "، ".join(names) + ". راجع البطاقات أدناه لكل موضوع على حدة." ) if ar else
                        ("The search shows trusted information related to " + ", ".join(names) + ". Review the cards below for each topic separately."))

    context = ""
    if isinstance(search_result, dict):
        safe = {
            "title": search_result.get("title"),
            "what": search_result.get("what"),
            "causes": (search_result.get("causes") or [])[:5],
            "worry": search_result.get("worry"),
            "doctor": search_result.get("doctor"),
            "matched_topics": [
                {"title": t.get("title"), "what": t.get("what"), "causes": (t.get("causes") or [])[:4], "worry": t.get("worry")}
                for t in (search_result.get("matched_topics") or [])[:3] if isinstance(t, dict)
            ],
        }
        context = json.dumps(safe, ensure_ascii=False)[:5000]
    try:
        # Only send the exact free-text question to the external assistant when
        # the user has already allowed service processing.
        if not _service_consent_ok():
            raise RuntimeError("service_consent_required_for_external_search_answer")
        client = analysis_core._groq_client()
        prompt = (
            ("أنت مساعد بحث صحي توعوي داخل SymptoSense. أجب عن سؤال المستخدم كاملًا كما كُتب، ولا تختزل السؤال إلى اسم العرض فقط. "
             "اعتبر كل كلمات السياق جزءًا أساسيًا من السؤال: التوقيت، المكان، العمر، الحمل أو الدورة، الطعام، النوم، الأدوية، التحاليل، الأمراض المزمنة والمدة. "
             "يمكن أن يكون السؤال عن عرض، مرض، دواء، تحليل، تغذية، نوم، صحة نفسية، حمل/دورة، إسعاف أو معلومة صحية عامة. "
             "استخدم السياق الطبي المنظم فقط إذا كان مرتبطًا فعلًا بالسؤال، ولا تخترع تشخيصًا أو جرعة دوائية ولا تطلب إيقاف/بدء دواء موصوف. "
             "إذا لم تعرف المصطلح أو لم تكن المعلومات كافية، قل ذلك بوضوح ثم أعطِ أقرب إرشاد آمن متعلق بالسؤال نفسه؛ لا تُرجع إجابة فارغة ولا تستبدل الموضوع بموضوع مختلف. "
             "أجب مباشرة في 2-4 جمل قصيرة، واذكر علامة خطر فقط إذا كانت مرتبطة بالسؤال.\n"
             if ar else
             "You are SymptoSense's educational health-search assistant. Answer the user's complete health query exactly as asked; never reduce it to one fuzzy symptom keyword. "
             "Treat timing, location, age, pregnancy/period context, food, sleep, medicines, lab tests, chronic conditions, and duration as essential modifiers. "
             "The query may concern a symptom, condition, medicine, lab test, nutrition, sleep, mental wellbeing, pregnancy/periods, first aid, or general health information. "
             "Use structured context only when it is truly relevant; do not diagnose, prescribe doses, or advise starting/stopping prescribed medication. "
             "If the term is unknown or information is insufficient, say so clearly and give the closest safe guidance that still addresses the same query; never return a blank answer or substitute an unrelated topic. Answer directly in 2-4 short sentences.\n")
            + ("سؤال المستخدم: " if ar else "User question: ") + q + "\n"
            + ("سياق البحث المنظم: " if ar else "Structured search context: ") + context
        )
        r = client.chat.completions.create(
            model=os.environ.get("GROQ_TEXT_MODEL", "openai/gpt-oss-120b").strip() or "openai/gpt-oss-120b",
            messages=[{"role":"user","content":prompt}],
            temperature=0.25,
            max_completion_tokens=220,
            timeout=8,
        )
        answer = str(r.choices[0].message.content or "").strip()
        if answer:
            return _strip_search_answer_heading(_assistant_compact_response(answer, lang, "search"), lang)
    except Exception:
        logging.getLogger(__name__).warning("Handled exception in _health_search_question_answer; fallback applied (handler 17801)")
        pass

    # Local fallback: a non-empty health search must always return a useful,
    # honest result even when the external AI service is unavailable. Never
    # substitute an unrelated fuzzy topic merely to avoid an empty response.
    if isinstance(search_result, dict):
        topics = search_result.get("matched_topics") or []
        if topics:
            names = [str(t.get("title") or "").strip() for t in topics[:2] if str(t.get("title") or "").strip()]
            if names:
                return (("سؤالك يجمع بين " + " و".join(names) + ". المعلومات أدناه تشرح الأجزاء المرتبطة، لكن لا يمكن تأكيد العلاقة بينها من البحث وحده. إذا ذكرت التوقيت والمدة والأدوية أو النتائج المرتبطة يمكن تضييق الإجابة أكثر.") if ar else
                        ("Your question combines " + " and ".join(names) + ". The information below explains the related parts, but the relationship cannot be confirmed from search alone. Adding timing, duration, medicines, or related results can make the answer more specific."))
        what = str(search_result.get("what") or "").strip()
        if what:
            return what

    # Universal safe fallback for queries that are not covered by the structured
    # search index. Reuse the curated local assistant fallback first so common
    # natural-language questions (for example painless knee clicking) still get
    # a directly useful answer when the external provider is offline.
    local_general = _assistant_general_local_fallback(q, lang)
    if local_general:
        return _strip_search_answer_heading(_assistant_compact_response(local_general, lang, "search"), lang)
    emoji, category = _health_search_topic_meta(q, lang)
    if ar:
        if category == "medication":
            return (f"بحثك هو: «{q}». لم أجد في قاعدة المعرفة المحلية معلومة موثوقة كافية عن هذا الدواء أو العلاقة المذكورة، لذلك لن أستبدلها بمعلومة عن دواء آخر. "
                    "اكتب اسم الدواء كما يظهر على العبوة مع العرض أو السؤال الذي تريد معرفته، وإذا كانت خدمة المساعد الذكي مفعّلة فسيجيب عن العلاقة كاملة.")
        if category == "test":
            return (f"بحثك هو: «{q}». لا توجد لدي حاليًا بيانات محلية كافية لتفسير هذه النتيجة بدقة من الاسم وحده. "
                    "أضف اسم الفحص والقيمة والوحدة والمدى المرجعي إن وُجد، وسأتعامل معها كسؤال واحد بدل تخمين نتيجة غير مرتبطة.")
        return (f"بحثك هو: «{q}». لم أجد تطابقًا موثوقًا كافيًا في قاعدة المعرفة المحلية، لذلك لن أعرض موضوعًا مختلفًا لمجرد أنه قريب في الاسم. "
                "إذا كانت خدمة المساعد الذكي مفعّلة فسيجيب عن السؤال كاملًا؛ ويمكنك أيضًا إضافة العمر، المدة، التوقيت، الأدوية أو الأعراض المصاحبة للحصول على إجابة أدق.")
    if category == "medication":
        return (f"Your search is: “{q}”. I do not have enough trusted local information about this medicine or the relationship you mentioned, so I will not substitute an unrelated medicine. "
                "Enter the medicine name as shown on the package together with the symptom or question; when the AI assistant is enabled it can answer the full relationship.")
    if category == "test":
        return (f"Your search is: “{q}”. I do not have enough local information to interpret this result accurately from the name alone. "
                "Add the test name, value, unit, and reference range when available so the whole question can be interpreted together.")
    return (f"Your search is: “{q}”. I could not find a sufficiently reliable local match, so I will not show an unrelated topic just because its wording is similar. "
            "When the AI assistant is enabled it can answer the full question; adding age, duration, timing, medicines, or accompanying symptoms can also make the answer more specific.")


def bind(namespace):
    """Inject the webapp helpers this module needs (proxies, resolved lazily on every call)."""
    missing = [n for n in DEPS if n not in namespace]
    if missing:
        raise RuntimeError("services.search_answers: missing dependencies %s" % missing)
    g = globals()
    for n in DEPS:
        g[n] = _inject.dependency(namespace, n)
