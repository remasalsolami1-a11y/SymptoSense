def _pdf_report(result, lang="ar"):
    """Create the symptom-analysis PDF from the already-saved analysis result.

    Uses PyMuPDF Story so Arabic shaping/RTL work without relying on a bundled
    application font. No medical values are recalculated here: this function
    only formats the data already stored for the analysis.
    """
    import html as _html
    try:
        import fitz
    except ImportError as exc:
        raise RuntimeError("PDF renderer is unavailable") from exc

    ar = lang != "en"

    def esc(value):
        return _html.escape(str(value if value not in (None, "") else "—"))

    def as_lines(value):
        if value in (None, "", []):
            return []
        if isinstance(value, (tuple, list)):
            out = []
            for item in value:
                if isinstance(item, dict):
                    text = item.get("tip") or item.get("text") or item.get("message") or item.get("name") or item.get("title") or ""
                    if text:
                        out.append(str(text))
                elif item not in (None, ""):
                    out.append(str(item))
            return out
        text = str(value).replace("\r", "\n")
        parts = []
        for line in text.split("\n"):
            line = re.sub(r"^\s*[-•*]+\s*", "", line).strip()
            if line:
                parts.append(line)
        return parts or [text.strip()]

    def data_quality_text():
        dq = result.get("data_quality")
        if isinstance(dq, dict):
            val = dq.get("percentage")
            if val is None:
                val = dq.get("percent")
            if val is None:
                val = dq.get("score")
            label = dq.get("label_ar" if ar else "label_en") or dq.get("label") or ""
            if val is not None:
                try:
                    val = round(float(val))
                    return (f"{val}% - {label}" if label else f"{val}%")
                except (TypeError, ValueError, OverflowError):
                    logging.getLogger(__name__).debug("Handled exception in data_quality_text; fallback applied (handler 16016)")
                    pass
        if isinstance(dq, (int, float)):
            return f"{round(float(dq))}%"
        return "—"

    risk = str(result.get("urgency") or result.get("risk_level") or "low").lower()
    risk_labels = ({
        "low": "خطورة منخفضة", "monitor": "خطورة منخفضة", "medium": "يحتاج مراجعة طبية",
        "review": "يحتاج مراجعة طبية", "high": "طوارئ", "urgent": "طوارئ", "emergency": "طوارئ",
    } if ar else {
        "low": "Low risk", "monitor": "Low risk", "medium": "Needs medical review",
        "review": "Needs medical review", "high": "Emergency", "urgent": "Emergency", "emergency": "Emergency",
    })
    risk_label = result.get("risk_label") or risk_labels.get(risk) or ("تقييم صحي" if ar else "Health assessment")

    symptoms = result.get("symptoms") or []
    if not isinstance(symptoms, list):
        symptoms = as_lines(symptoms)
    symptom_text = ("، ".join(map(str, symptoms)) if ar else ", ".join(map(str, symptoms))) or "—"
    gender_raw = str(result.get("gender") or "").strip().lower()
    if ar:
        gender = {"f":"أنثى", "female":"أنثى", "m":"ذكر", "male":"ذكر"}.get(gender_raw, result.get("gender") or "—")
    else:
        gender = {"f":"Female", "female":"Female", "m":"Male", "male":"Male"}.get(gender_raw, result.get("gender") or "—")

    conditions = result.get("knowledge_matches") or []
    condition_blocks = []
    for item in conditions:
        if not isinstance(item, dict):
            continue
        name = (item.get("name_ar") if ar else item.get("name_en")) or item.get("name") or item.get("disease_name") or ""
        if not name:
            continue
        score = item.get("score")
        if score is None:
            score = item.get("matching_score")
        if score is None:
            score = item.get("match_score")
        score_html = ""
        if score not in (None, ""):
            score_html = f'<span class="pill">{esc("التوافق" if ar else "Match")}: {esc(score)}</span>'
        reason = item.get("why") or item.get("reason") or item.get("match_reason") or ""
        direct_source = item.get("explanation_source")
        if not isinstance(direct_source, dict):
            item_sources = item.get("sources") or []
            direct_source = item_sources[0] if item_sources and isinstance(item_sources[0], dict) else None
        direct_source_html = ""
        if direct_source:
            source_name = direct_source.get("source_name") or direct_source.get("organization") or direct_source.get("name") or ""
            source_title = (direct_source.get("reference_title_ar") if ar else direct_source.get("reference_title_en")) or direct_source.get("reference_title_en") or direct_source.get("reference_title_ar") or source_name
            source_url = direct_source.get("reference_url") or direct_source.get("official_url") or direct_source.get("url") or ""
            source_scope = str(direct_source.get("source_scope") or "")
            source_label = (("مرجع داعم للسياق" if ar else "Supporting context source")
                            if source_scope == "symptom_context_fallback"
                            else ("مرجع هذا التفسير" if ar else "Source for this explanation"))
            source_text = source_title or source_name
            if source_text:
                if source_url:
                    direct_source_html = '<p class="condition-source"><b>%s:</b> <a href="%s">%s</a></p>' % (esc(source_label), esc(source_url), esc(source_text))
                else:
                    direct_source_html = '<p class="condition-source"><b>%s:</b> %s</p>' % (esc(source_label), esc(source_text))
        condition_blocks.append(
            '<div class="condition"><div class="condition-head"><strong>%s</strong>%s</div>%s%s</div>' % (
                esc(name), score_html, ('<p>%s</p>' % esc(reason)) if reason else '', direct_source_html
            )
        )
    if not condition_blocks:
        raw_pc = result.get("possible_conditions") or ""
        if raw_pc:
            condition_blocks.append('<div class="condition"><p>%s</p></div>' % esc(raw_pc))

    recommendations = result.get("recommendations") or []
    rec_lines = as_lines(recommendations)
    danger_lines = as_lines(result.get("danger_signs"))
    home_lines = as_lines(result.get("home_care"))
    seek_lines = as_lines(result.get("when_to_seek_care"))
    doctor_lines = as_lines(result.get("questions_for_doctor"))

    source_cards = []
    for src in (result.get("medical_sources") or []):
        if not isinstance(src, dict):
            continue
        name = src.get("source_name") or src.get("organization") or src.get("name") or ("مصدر طبي" if ar else "Medical source")
        title = (src.get("reference_title_ar") if ar else src.get("reference_title_en")) or src.get("reference_title_en") or src.get("reference_title_ar") or ""
        source_url = src.get("reference_url") or src.get("official_url") or src.get("url") or ""
        source_link = ('<small><a href="%s">%s</a></small>' % (esc(source_url), esc(title or name))) if source_url else (('<small>%s</small>' % esc(title)) if title else '')
        source_cards.append('<div class="source"><strong>%s</strong>%s</div>' % (esc(name), source_link))

    labels = ({
        "title":"تقرير تحليل الأعراض", "subtitle":"SymptoSense - ملخص صحي توعوي",
        "summary":"نتيجة التحليل", "risk":"مستوى الخطورة", "quality":"اكتمال المعلومات المدخلة",
        "entered":"المعلومات المدخلة", "symptoms":"الأعراض", "duration":"المدة", "severity":"شدة الأعراض",
        "age":"العمر", "gender":"الجنس", "conditions":"الاحتمالات المحتملة", "now":"ماذا أفعل الآن؟",
        "warnings":"علامات تستدعي الانتباه", "home":"الرعاية المنزلية", "doctor":"أسئلة للطبيب",
        "sources":"المصادر الطبية", "none":"لم يتم تحديد معلومات إضافية ضمن هذا القسم.",
        "disclaimer":"هذه النتيجة توعوية ولا تقدم تشخيصًا طبيًا، ولا تغني عن استشارة مختص صحي عند الحاجة.",
        "generated":"تاريخ إنشاء التقرير",
    } if ar else {
        "title":"Symptom Analysis Report", "subtitle":"SymptoSense - Educational health summary",
        "summary":"Analysis result", "risk":"Risk level", "quality":"Information completeness",
        "entered":"Information entered", "symptoms":"Symptoms", "duration":"Duration", "severity":"Symptom severity",
        "age":"Age", "gender":"Gender", "conditions":"Possible conditions", "now":"What should I do now?",
        "warnings":"Warning signs", "home":"Home care", "doctor":"Questions for your clinician",
        "sources":"Medical sources", "none":"No additional information was provided for this section.",
        "disclaimer":"This result is educational and does not provide a medical diagnosis or replace professional medical advice when needed.",
        "generated":"Report generated",
    })

    def list_html(lines, empty=False):
        if not lines:
            return ('<p class="muted">%s</p>' % esc(labels["none"])) if empty else ""
        return '<ul>%s</ul>' % ''.join('<li>%s</li>' % esc(x) for x in lines)

    direction = "rtl" if ar else "ltr"
    align = "right" if ar else "left"
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    html_doc = f"""<!doctype html>
<html><head><meta charset="utf-8"><style>
*{{box-sizing:border-box}} body{{font-family:sans-serif;color:#23384A;font-size:10.5pt;line-height:1.55;direction:{direction};text-align:{align};}}
h1{{font-size:22pt;color:#163B5C;margin:0 0 4px}} h2{{font-size:14pt;color:#163B5C;margin:0 0 10px}} p{{margin:4px 0 8px}}
.header{{border-bottom:2px solid #DCE8F0;padding-bottom:14px;margin-bottom:16px}} .muted{{color:#566a7d}} .card{{border:1px solid #DCE8F0;border-radius:12px;padding:14px;margin:0 0 12px;background:#FFFFFF}}
.summary{{background:#F3F9FD}} .risk{{font-size:16pt;font-weight:700;color:#163B5C}} .pill{{display:inline-block;border:1px solid #DCE8F0;border-radius:999px;padding:2px 8px;font-size:8.5pt;color:#566a7d}}
.grid{{display:flex;flex-wrap:wrap;gap:8px}} .field{{width:48%;border:1px solid #E4EDF3;border-radius:9px;padding:8px}} .field b{{display:block;color:#566a7d;font-size:8.5pt;margin-bottom:2px}}
.condition,.source{{border:1px solid #E4EDF3;border-radius:9px;padding:10px;margin:7px 0}} .condition-head{{display:flex;justify-content:space-between;gap:8px;align-items:center}} .condition-source{{font-size:8.7pt;color:#49677D;margin-top:6px}} .condition-source a,.source a{{color:#1f6fae;text-decoration:none}} .source small{{display:block;color:#566a7d;margin-top:3px}}
ul{{margin:4px 0 0;padding-{'right' if ar else 'left'}:20px}} li{{margin:3px 0}} .disclaimer{{border:1px solid #EFDAA7;background:#FFF8E7;border-radius:10px;padding:10px;color:#6F531B;margin-top:15px}}
</style></head><body>
<div class="header"><h1>{esc(labels['title'])}</h1><p class="muted">{esc(labels['subtitle'])}</p><p class="muted">{esc(labels['generated'])}: {esc(generated)}</p></div>
<div class="card summary"><h2>{esc(labels['summary'])}</h2><div class="risk">{esc(labels['risk'])}: {esc(risk_label)}</div><p><b>{esc(labels['quality'])}:</b> {esc(data_quality_text())}</p></div>
<div class="card"><h2>{esc(labels['entered'])}</h2><div class="grid">
<div class="field"><b>{esc(labels['symptoms'])}</b>{esc(symptom_text)}</div>
<div class="field"><b>{esc(labels['duration'])}</b>{esc(result.get('duration'))}</div>
<div class="field"><b>{esc(labels['severity'])}</b>{esc(result.get('severity'))}</div>
<div class="field"><b>{esc(labels['age'])}</b>{esc(result.get('age'))}</div>
<div class="field"><b>{esc(labels['gender'])}</b>{esc(gender)}</div>
</div></div>
<div class="card"><h2>{esc(labels['conditions'])}</h2>{''.join(condition_blocks) or '<p class="muted">'+esc(labels['none'])+'</p>'}</div>
<div class="card"><h2>{esc(labels['now'])}</h2>{list_html(rec_lines + seek_lines, True)}</div>
<div class="card"><h2>{esc(labels['warnings'])}</h2>{list_html(danger_lines, True)}</div>
{('<div class="card"><h2>'+esc(labels['home'])+'</h2>'+list_html(home_lines)+'</div>') if home_lines else ''}
{('<div class="card"><h2>'+esc(labels['doctor'])+'</h2>'+list_html(doctor_lines)+'</div>') if doctor_lines else ''}
{('<div class="card"><h2>'+esc(labels['sources'])+'</h2>'+''.join(source_cards)+'</div>') if source_cards else ''}
<div class="disclaimer">{esc(labels['disclaimer'])}</div>
</body></html>"""

    buf = io.BytesIO()
    writer = fitz.DocumentWriter(buf)
    page = fitz.paper_rect("a4")
    story = fitz.Story(html=html_doc)
    more = True
    page_count = 0
    try:
        while more:
            page_count += 1
            if page_count > 40:
                raise RuntimeError("PDF exceeded safe page limit")
            device = writer.begin_page(page)
            more, _ = story.place(fitz.Rect(42, 42, page.width - 42, page.height - 42))
            story.draw(device)
            writer.end_page()
    finally:
        writer.close()
    buf.seek(0)
    if not buf.getvalue().startswith(b"%PDF"):
        raise RuntimeError("Invalid PDF output")
    return buf



def _assistant_general_local_fallback(text, lang):
    """Demo-safe local fallback for health questions outside the curated index.

    It preserves the user's full query, avoids diagnosis, and gives a relevant
    next step even when the external provider is unavailable.
    """
    query = " ".join(str(text or "").strip().split())[:600]
    if not query:
        return None
    low = query.lower()
    ar = lang != "en"

    # Common real-world demo query: painless knee clicking/crepitus.
    knee = any(k in low for k in ("ركب", "knee"))
    click = any(k in low for k in ("طقط", "فرقع", "صوت", "click", "crack", "pop", "crepitus"))
    no_pain = any(k in low for k in ("بدون ألم", "بدون الم", "ما فيه ألم", "مافي ألم", "no pain", "painless"))
    if knee and click:
        if ar:
            base = (
                "طقطقة الركبة قد تحدث مع حركة الأوتار أو الأنسجة أو فقاعات صغيرة داخل المفصل، "
                "وقد تكون شائعة إذا لم يصاحبها ألم أو تورم أو عدم ثبات. "
            )
            if not no_pain:
                base += "وجود ألم أو تورم أو قفل بالمفصل يغيّر التقييم. "
            return base + "راجع مختصًا إذا بدأت بعد إصابة، أو ظهر ألم/تورم/احمرار، أو صارت الركبة تعلق أو تخونك. هذه معلومات توعوية وليست تشخيصًا."
        base = "Knee clicking can occur from normal movement of tendons/tissues or small gas bubbles in the joint, and it is often benign when there is no pain, swelling, or instability. "
        if not no_pain:
            base += "Pain, swelling, locking, or giving-way changes the picture. "
        return base + "Seek medical review if it followed an injury or you develop pain, swelling, redness, locking, or instability. This is educational information, not a diagnosis."

    # Category-aware fallback: useful without pretending the local KB knows the answer.
    groups = [
        (("دواء", "أدوية", "حبة", "جرعة", "medicine", "medication", "drug", "dose"),
         "سؤالك يبدو متعلقًا بدواء. لا أؤكد جرعة أو تداخلًا دون اسم الدواء والتركيز وما الأدوية الأخرى المستخدمة. اذكر الاسم كما على العبوة، ولا تبدأ أو توقف دواءً موصوفًا من نفسك.",
         "Your question appears medication-related. I cannot safely confirm a dose or interaction without the exact medicine, strength, and other medicines used. Share the label name, and do not start or stop a prescribed medicine on your own."),
        (("تحليل", "مختبر", "cbc", "wbc", "hgb", "سكر", "lab", "test result", "blood test"),
         "سؤالك يبدو متعلقًا بنتيجة تحليل. اكتب اسم الفحص والقيمة والوحدة والمدى المرجعي المكتوب في المختبر؛ التفسير يعتمد على هذه التفاصيل والسياق الصحي.",
         "Your question appears to be about a lab result. Share the test name, value, unit, and the laboratory reference range; interpretation depends on those details and clinical context."),
        (("دورة", "حيض", "حمل", "مهبل", "period", "menstrual", "pregnan", "vaginal"),
         "سؤالك يتعلق بالصحة النسائية. التوقيت بالنسبة للدورة أو احتمال الحمل، شدة الألم أو النزف، ووجود دوخة أو إغماء تفاصيل مهمة. إذا كان هناك نزيف شديد جدًا أو ألم شديد مفاجئ أو إغماء فاطلب تقييمًا عاجلًا.",
         "Your question relates to menstrual/pregnancy health. Timing, pregnancy possibility, pain/bleeding severity, and faintness are important. Seek urgent care for very heavy bleeding, sudden severe pain, or fainting."),
        (("نوم", "أرق", "تعب", "sleep", "insomnia", "fatigue"),
         "سؤالك يتعلق بالنوم أو الإرهاق. المدة، عدد ساعات النوم، الأدوية/الكافيين، ووجود أعراض أخرى مثل ضيق النفس أو فقدان وزن تساعد على فهمه. إذا استمر أو أثر في يومك فراجع مختصًا.",
         "Your question relates to sleep or fatigue. Duration, sleep hours, medicines/caffeine, and other symptoms such as breathlessness or weight loss help clarify it. Seek medical review if it persists or disrupts daily life."),
        (("جلد", "طفح", "حكة", "rash", "skin", "itch"),
         "سؤالك يبدو متعلقًا بالجلد. صف الشكل والمكان والمدة وهل يوجد دواء/طعام جديد. صعوبة التنفس أو تورم الشفاه/اللسان مع طفح تستدعي مساعدة عاجلة.",
         "Your question appears skin-related. Describe appearance, location, duration, and any new medicine/food. A rash with breathing difficulty or lip/tongue swelling needs urgent help."),
        (("بول", "تبول", "urine", "urinary", "pee"),
         "سؤالك يبدو متعلقًا بالمسالك البولية. وجود حرقة أو دم أو حرارة أو ألم بالخاصرة أو صعوبة شديدة في التبول يغيّر درجة الاستعجال؛ اذكر هذه التفاصيل إن وجدت.",
         "Your question appears urinary. Burning, blood, fever, flank pain, or major difficulty urinating changes urgency; include those details if present."),
    ]
    for keys, ara, eng in groups:
        if any(k in low for k in keys):
            return (ara if ar else eng) + (" هذه معلومات توعوية وليست تشخيصًا." if ar else " This is educational information, not a diagnosis.")

    # Reuse the full symptom dictionary when the smaller explanation index has
    # no entry. Do not invent a condition simply to produce a named result.
    symptom_rows = getattr(medical_knowledge, "SYMPTOMS", [])
    recognised = []
    for row in symptom_rows:
        aliases = [row[1], row[2]] + list(row[4]) + list(row[5])
        if any(_assistant_phrase_present(query, alias) for alias in aliases):
            recognised.append(row)
    if recognised:
        names = list(dict.fromkeys(row[1] if ar else row[2] for row in recognised))[:3]
        category = recognised[0][3]
        prompts = {
            "pain": ("أين مكان الألم بالضبط، وهل بدأ فجأة؟", "Where exactly is the pain, and did it start suddenly?"),
            "digestive": ("هل يرتبط بالأكل أو بتغيّر التبرز؟", "Does it relate to meals or a change in bowel habits?"),
            "respiratory": ("هل يحدث في الراحة أم مع المجهود؟", "Does it occur at rest or with activity?"),
            "neurological": ("هل بدأ فجأة أم تدريجيًا، وهل يؤثر في نشاطك؟", "Did it start suddenly or gradually, and does it affect your activities?"),
            "skin": ("أين يظهر، وهل تغيّر شكله أو انتشر؟", "Where is it, and has it changed or spread?"),
        }
        question = prompts.get(category, ("متى بدأ، وهل يستمر أم يأتي على فترات؟", "When did it start, and is it constant or intermittent?"))[0 if ar else 1]
        return (("فهمت أنك تسأل عن «" + query + "»، ويتضمن: " + "، ".join(names) + ". لا تكفي هذه المعلومات لتحديد السبب. " + question +
                 " إذا كان العرض شديدًا أو مفاجئًا أو صاحبه إغماء أو صعوبة تنفس أو ألم صدر، اطلب تقييمًا عاجلًا.") if ar else
                ("Your question “" + query + "” includes: " + ", ".join(names) + ". This is not enough to establish the cause. " + question +
                 " Seek urgent assessment for severe or sudden symptoms, fainting, breathing difficulty, or chest pain."))

    return (
        "أفهم سؤالك: «" + query + "». لا توجد مطابقة موثوقة كافية في قاعدة المعرفة المحلية لأعطي سببًا محددًا دون تخمين. "
        "اذكر متى بدأ، المدة، الشدة، وما الذي يزيده أو يخففه وأي أدوية/أعراض مصاحبة؛ وإذا كان العرض شديدًا أو مفاجئًا أو معه صعوبة تنفس أو ألم صدر أو إغماء فاطلب تقييمًا عاجلًا. هذه معلومات توعوية وليست تشخيصًا."
        if ar else
        "I understand your question: “" + query + "”. The local knowledge base does not have a reliable enough direct match to name a cause without guessing. "
        "Add onset, duration, severity, triggers/relievers, medicines, and associated symptoms; seek urgent care for severe/sudden symptoms, breathing difficulty, chest pain, or fainting. This is educational information, not a diagnosis."
    )



def _health_search_relation_result(query, lang):
    """Build a relationship-first result for medicine + symptom queries.

    If a medicine is present, the search must never fall back to a standalone
    symptom card.  The relationship itself becomes the primary result.
    """
    q = " ".join(str(query or "").strip().split())[:600]
    if not q:
        return None
    ar = lang != "en"
    med = _health_search_medication_context(q, lang)
    if not med:
        return None

    symptom = _health_search_symptom_for_relation(q, lang, med)
    med_name = str((med.get("name_ar") if ar else med.get("name_en")) or ("الدواء" if ar else "the medicine")).strip()
