@route("/api/admin/quality-dashboard", methods=["GET"])
def api_admin_quality_dashboard():
    """Privacy-safe quality signals for symptom and laboratory analysis.

    Metrics are operational/verification indicators, not diagnostic accuracy.
    No symptom text, lab values, names, emails, or uploaded files are returned.
    """
    try:
        try:
            days = max(1, min(365, int(request.args.get("days") or 30)))
        except (TypeError, ValueError):
            days = 30
        db.init_db(); platform_v2.init_schema()
        since = (datetime.now(timezone.utc) - timedelta(days=days)).isoformat()
        conn = db._conn(); cur = conn.cursor()
        try:
            def scalar(sql, params=()):
                cur.execute(sql, params)
                row = cur.fetchone()
                return int((row or [0])[0] or 0)

            symptom_success = scalar(
                f"SELECT COUNT(*) FROM ss_usage_events WHERE created_at>={db.PH} AND path='/api/analyze' AND event_type='analysis_complete'",
                (since,),
            )
            symptom_failed = scalar(
                f"SELECT COUNT(*) FROM ss_usage_events WHERE created_at>={db.PH} AND path='/api/analyze' AND event_type='error'",
                (since,),
            )
            safety_alerts = scalar(
                f"SELECT COUNT(*) FROM ss_usage_events WHERE created_at>={db.PH} AND service='symptom_analysis' AND event_type='safety_alert'",
                (since,),
            )
            blood_extract_success = scalar(
                f"SELECT COUNT(*) FROM ss_usage_events WHERE created_at>={db.PH} AND path='/api/blood' AND event_type='blood_extract_complete'",
                (since,),
            )
            blood_analysis_success = scalar(
                f"SELECT COUNT(*) FROM ss_usage_events WHERE created_at>={db.PH} AND path='/api/blood' AND event_type='blood_analysis_complete'",
                (since,),
            )
            blood_failed = scalar(
                f"SELECT COUNT(*) FROM ss_usage_events WHERE created_at>={db.PH} AND path='/api/blood' AND event_type='error'",
                (since,),
            )
            cur.execute(
                f"SELECT data FROM blood_tests WHERE timestamp>={db.PH} ORDER BY timestamp DESC",
                (since,),
            )
            blood_rows = cur.fetchall()
        finally:
            conn.close()

        saved_blood = 0
        confirmed_blood = 0
        files_with_meta = 0
        full_file_reads = 0
        pages_total = 0
        pages_read = 0
        total_indicators = 0
        sourced_indicators = 0
        needs_review_values = 0
        for row in blood_rows:
            raw = row[0] if row else None
            try:
                data = json.loads(raw) if isinstance(raw, str) else (raw or {})
            except (TypeError, ValueError, OverflowError):
                continue
            if not isinstance(data, dict):
                continue
            saved_blood += 1
            confirmed_blood += int(bool(data.get("confirmed_by_user")))
            meta = data.get("extraction_meta") if isinstance(data.get("extraction_meta"), dict) else {}
            if meta and bool(meta.get("server_verified")):
                # V153: completeness metrics only use metadata that was issued
                # by the server during the actual upload/extraction request.
                files_with_meta += 1
                try: pt = max(0, int(meta.get("pages_total") or 0))
                except (TypeError, ValueError): pt = 0
                try: pr = max(0, int(meta.get("pages_read") or 0))
                except (TypeError, ValueError): pr = 0
                pages_total += pt; pages_read += min(pr, pt) if pt else pr
                full_file_reads += int(bool(meta.get("complete_page_read")) and (not pt or pr >= pt))
            indicators = data.get("indicators") if isinstance(data.get("indicators"), list) else []
            for item in indicators:
                if not isinstance(item, dict):
                    continue
                total_indicators += 1
                src = item.get("source") if isinstance(item.get("source"), dict) else {}
                if src.get("url"):
                    sourced_indicators += 1
            verification = data.get("verification") if isinstance(data.get("verification"), dict) else {}
            counts = verification.get("counts") if isinstance(verification.get("counts"), dict) else {}
            needs_review_values += int(counts.get("needs_review") or 0) + int(counts.get("fallback_reference") or 0)

        safety_validation = safety_engine.validation_report()
        try:
            knowledge = medical_knowledge.statistics()
        except Exception:
            knowledge = {}

        symptom_total = symptom_success + symptom_failed
        blood_total = blood_analysis_success + blood_failed
        source_pct = round(sourced_indicators * 100.0 / total_indicators, 1) if total_indicators else 0.0
        full_read_pct = round(full_file_reads * 100.0 / files_with_meta, 1) if files_with_meta else 0.0
        return jsonify({
            "ok": True,
            "days": days,
            "symptoms": {
                "completed": symptom_success,
                "failed": symptom_failed,
                "success_rate": round(symptom_success * 100.0 / symptom_total, 1) if symptom_total else None,
                "safety_alerts": safety_alerts,
                "safety_validation": safety_validation,
                "knowledge_source_coverage_pct": knowledge.get("source_coverage_pct"),
                "symptom_support_coverage_pct": knowledge.get("symptom_support_coverage_pct"),
            },
            "blood": {
                "extractions_completed": blood_extract_success,
                "analyses_completed": blood_analysis_success,
                "failed_requests": blood_failed,
                "success_rate": round(blood_analysis_success * 100.0 / blood_total, 1) if blood_total else None,
                "saved_analyses": saved_blood,
                "confirmed_by_user": confirmed_blood,
                "files_with_completeness_metadata": files_with_meta,
                "full_file_reads": full_file_reads,
                "full_file_read_rate": full_read_pct if files_with_meta else None,
                "pages_read": pages_read,
                "pages_total": pages_total,
                "values_needing_review": needs_review_values,
                "source_linked_values": sourced_indicators,
                "total_values": total_indicators,
                "source_coverage_pct": source_pct if total_indicators else None,
            },
            "notes": {
                "accuracy_claim": "These are operational and verification metrics, not clinical diagnostic accuracy.",
                "telemetry_scope": "Request success/failure metrics include only sessions where optional analytics telemetry was permitted; saved blood-analysis aggregates are date-scoped, explicitly consented, and file-completeness counts use server-verified extraction metadata only.",
            },
        })
    except Exception as exc:
        return _mk_error(exc, 500)


