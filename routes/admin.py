        best_effort.call(platform_v2.audit, int(_ss_user_id()), 'public_launch_reset', 'admin_data', 'all_test_data', None, {'removed_users': int(summary.get('removed_users') or 0), 'deleted_rows': int(summary.get('deleted_rows') or 0), 'preserved_admin': True, 'preserved_medical_knowledge': True})
