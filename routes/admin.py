@route("/api/admin/profile/password", methods=["POST"])
def api_admin_profile_password():
    data=request.get_json(silent=True) or {}
    current=str(data.get("current_password") or ""); new=str(data.get("new_password") or "")
    confirm=str(data.get("confirm_password") or "")
    if not hmac.compare_digest(new,confirm):
        return jsonify({"ok":False,"error":"password_mismatch"}),400
    ok,error=db.change_ss_user_password(int(_ss_user_id()),current,new)
    if not ok:
        best_effort.call(platform_v2.audit, int(_ss_user_id()), 'password_change_failed', 'admin_security', 'self', None, {'status': 'failed', 'reason': error})
        return jsonify({"ok":False,"error":error}),400
    user_id=int(_ss_user_id())
    admin_security.rotate_epoch(user_id)
    platform_v2.audit(user_id,"password_changed","admin_security","self",None,{"status":"success","all_admin_sessions_revoked":True})
    # A password change is a security boundary: every old Admin session,
    # including this browser, must authenticate again and complete 2FA.
    session.clear()
    return jsonify({"ok":True,"message":"password_changed_reauth_required","login_url":"/login?next=/admin"})


