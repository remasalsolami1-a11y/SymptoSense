@route("/api/checkin", methods=["GET", "POST"])
def api_checkin():
    # Daily tracking is intentionally account-bound. Guest/session identifiers
    # are not used because the history must follow the signed-in user only.
    if not _ss_user_id():
        return jsonify({
            "ok": False,
            "login_required": True,
            "error": "سجّل الدخول لحفظ ومتابعة حالتك اليومية." if _lang() == "ar" else "Sign in to save and track your daily health status.",
        }), 401

    # Daily tracking intentionally avoids the full database migration pass.
    # Production Railway databases may contain legacy tables whose unrelated
    # migrations can fail even though daily tracking only needs user_data.
    # The db.save/get_web_daily_checkin helpers ensure the minimal user_data
    # storage they need without touching legacy daily_checkins migrations.
    account_id = _ss_user_id()
    if request.method == "POST":
        if not _service_consent_ok():
            return _consent_required_json("/checkin")
        try:
            data = request.get_json(force=True) or {}
            rating = int(data.get("rating"))
            if rating < 1 or rating > 5:
                return jsonify({"ok": False, "error": "التقييم من 1 إلى 5" if _lang() == "ar" else "Rating must be from 1 to 5"}), 400
            day = str(data.get("date") or "").strip()
            try:
                datetime.strptime(day, "%Y-%m-%d")
            except (TypeError, ValueError, OverflowError):
                logging.getLogger(__name__).debug("Handled exception in api_checkin; fallback applied (handler 16983)")
                return jsonify({"ok": False, "error": "invalid_date"}), 400
            saved = db.save_web_daily_checkin(account_id, rating, day)
            payload = _checkin_api_payload(account_id, day)
            payload.update({"created": bool(saved.get("created")), "updated": not bool(saved.get("created"))})
            return jsonify(payload)
        except Exception as e:
            request_id = getattr(g, "request_id", "")
            app.logger.exception("Daily check-in save failed; request_id=%s error_type=%s", request_id, type(e).__name__)
            return jsonify({
                "ok": False,
                "error": "تعذر حفظ تسجيل الحالة الآن." if _lang() == "ar" else "Unable to save the daily check-in right now.",
                "error_code": "checkin_save_failed",
                "request_id": request_id,
            }), 500

    try:
        day = str(request.args.get("date") or datetime.now(timezone.utc).date().isoformat()).strip()
        try:
            datetime.strptime(day, "%Y-%m-%d")
        except (TypeError, ValueError, OverflowError):
            logging.getLogger(__name__).debug("Handled exception in api_checkin; fallback applied (handler 17003)")
            day = datetime.now(timezone.utc).date().isoformat()
        return jsonify(_checkin_api_payload(account_id, day))
    except Exception as e:
        request_id = getattr(g, "request_id", "")
        app.logger.exception("Daily check-in load failed; request_id=%s error_type=%s", request_id, type(e).__name__)
        return jsonify({
            "ok": False,
            "error": "تعذر تحميل تسجيلات الحالة الآن." if _lang() == "ar" else "Unable to load daily check-ins right now.",
            "error_code": "checkin_load_failed",
            "request_id": request_id,
        }), 500


@route("/api/feedback", methods=["POST"])
def api_feedback():
    # Feedback is an explicit user submission, separate from optional analytics consent.
    try:
        data = request.get_json(force=True) or {}
        try:
            rating = int(data.get("rating"))
        except (TypeError, ValueError, OverflowError):
            logging.getLogger(__name__).debug("Handled exception in api_feedback; fallback applied (handler 17024)")
            return jsonify({"ok": False, "error": "rating_must_be_1_to_5"}), 400
        if rating < 1 or rating > 5:
            return jsonify({"ok": False, "error": "rating_must_be_1_to_5"}), 400
        comment = (data.get("comment") or "").strip()[:500]
        public_comment = bool(data.get("public_comment")) and bool(comment)
        allowed_reasons = {"clear", "helpful", "too_short", "too_long", "unclear", "not_relevant", "missing_detail", "other"}
        reason_code = str(data.get("reason_code") or "").strip().lower() or None
        if reason_code is not None and reason_code not in allowed_reasons:
            return jsonify({"ok": False, "error": "invalid_reason"}), 400
        allowed_contexts = {"analysis_result", "assistant", "search", "other"}
        context = str(data.get("context") or "analysis_result").strip().lower()
        if context not in allowed_contexts:
            return jsonify({"ok": False, "error": "invalid_context"}), 400
        record_id = None
        raw_record_id = data.get("record_id")
        if raw_record_id not in (None, "", 0, "0"):
            try:
                candidate_id = int(raw_record_id)
            except (TypeError, ValueError):
                return jsonify({"ok": False, "error": "invalid_record_id"}), 400
            if _ss_user_id():
                if not db.get_record_owned(_data_user_id(), candidate_id):
                    return jsonify({"ok": False, "error": "record_not_found"}), 404
                record_id = candidate_id
        db.init_db()
        db.save_feedback(_data_user_id(), record_id, "star:%d" % rating, comment or None, public_comment=public_comment, reason_code=reason_code, context=context)
        return jsonify({"ok": True, "public_comment": public_comment, "reason_code": reason_code})
    except Exception as e:
        return _mk_error(e, 500)


def register_routes(app, namespace):
    """Inject webapp dependencies, apply the original decorators, and add the URL rules (same endpoint names)."""
    missing = [n for n in DEPS if n not in namespace]
    if missing:
        raise RuntimeError("routes.tracking: missing dependencies %s" % missing)
    g = globals()
    for n in DEPS:
        g[n] = _inject.dependency(namespace, n)
    g["app"] = app
    for name, spec in _SPECS.items():
        view = spec["fn"]
        for w in reversed(_WRAPPERS.get(name, ())):
            view = _inject.resolve_wrapper(w, g)(view)
        for rule, opts in spec["rules"]:
            kw = dict(opts)
            endpoint = kw.pop("endpoint", name)
            app.add_url_rule(rule, endpoint=endpoint, view_func=view, **kw)
