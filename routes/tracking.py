def route(rule, **opts):
    def deco(fn):
        _SPECS.setdefault(fn.__name__, {"fn": fn, "rules": []})["rules"].append((rule, opts))
        return fn
    return deco


@route("/api/health-profile", methods=["GET", "POST"])
def api_health_profile():
    db.init_db()
    uid = _ss_user_id()
    if request.method == "GET":
        profile = db.load_health_profile(uid) or {}
        return jsonify({"ok": True, "profile": profile})
    if not _service_consent_ok():
        return _consent_required_json("/manage")
    try:
        data = request.get_json(force=True)
        if not isinstance(data, dict):
            return jsonify({"ok": False, "error": "invalid_input"}), 400
        existing = db.load_health_profile(uid) or {}
        # This endpoint is used for small incremental updates from the assistant.
        # Merge rather than replacing the full optional health profile, otherwise
        # a one-field update could erase medications/allergies/conditions.
        allowed = {"display_name", "dob", "gender", "height", "weight", "activity_level", "medications", "allergies", "health_conditions", "extra_info", "lang"}
        merged = dict(existing)
        incoming = {k: v for k, v in data.items() if k in allowed}
        for key, raw in list(incoming.items()):
            ok, cleaned = validate_profile_field(key, raw)
            if not ok:
                return jsonify({"ok": False, "error": cleaned, "field": key}), 400
            incoming[key] = cleaned
        merged.update(incoming)
        db.save_health_profile(uid, merged)
        return jsonify({"ok": True})
    except Exception as e:
        return _mk_error(e, 500)


