@route("/api/smart-followup", methods=["GET", "POST"])
def api_smart_followup():
    """Offer and record a privacy-preserving follow-up for the latest saved analysis."""
    uid = _ss_user_id()
    if not uid:
        return jsonify({"ok": True, "eligible": False, "logged_in": False})
    if not _service_consent_ok():
        if request.method == "POST":
            return _consent_required_json("/chat")
        return jsonify({"ok": True, "eligible": False, "logged_in": True, "reason": "consent_required"})
    db.init_db()
    privacy = db.load_privacy_settings(uid) or {}
    if not privacy.get("use_in_analysis", True):
        return jsonify({"ok": True, "eligible": False, "logged_in": True, "reason": "reuse_disabled"})
    user_key = _data_user_id()
    if request.method == "GET":
        records = db.get_records(user_key, limit=1, member_id=0)
        if not records:
            return jsonify({"ok": True, "eligible": False, "logged_in": True})
        rec = records[0]
        try:
            ts = datetime.fromisoformat(str(rec.get("timestamp") or "").replace("Z", "+00:00"))
            if ts.tzinfo is None:
                ts = ts.replace(tzinfo=timezone.utc)
            age_seconds = max(0.0, (datetime.now(timezone.utc) - ts.astimezone(timezone.utc)).total_seconds())
            age_days = int(age_seconds // 86400)
        except Exception:
            age_seconds = 10**12
            age_days = 9999
        # Do not ask immediately after an assessment; follow-up becomes useful
        # after enough time has passed to notice change, and expires after 30 days.
        if age_seconds < 12 * 3600:
            return jsonify({"ok": True, "eligible": False, "logged_in": True, "reason": "too_soon"})
        if age_days > 30:
            return jsonify({"ok": True, "eligible": False, "logged_in": True, "reason": "too_old"})
        latest_fu = db.get_latest_followup(user_key, rec.get("id"))
        if latest_fu:
            try:
                fu_ts = datetime.fromisoformat(str(latest_fu.get("timestamp") or "").replace("Z", "+00:00"))
                if fu_ts.tzinfo is None:
                    fu_ts = fu_ts.replace(tzinfo=timezone.utc)
                # Avoid prompting repeatedly on every visit after a recent answer.
                if (datetime.now(timezone.utc) - fu_ts.astimezone(timezone.utc)).total_seconds() < 20 * 3600:
                    return jsonify({"ok": True, "eligible": False, "logged_in": True, "reason": "recently_answered"})
            except Exception:
                pass
        return jsonify({"ok": True, "eligible": True, "logged_in": True, "analysis": rec, "age_days": age_days})

    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        return jsonify({"ok": False, "error": "invalid_json_object"}), 400
    try:
        record_id = int(data.get("record_id") or 0)
    except (TypeError, ValueError):
        return jsonify({"ok": False, "error": "invalid_record_id"}), 400
    try:
        outcome, new_sign = db.normalize_followup(data.get("outcome"), data.get("new_sign"))
    except ValueError:
        return jsonify({"ok": False, "error": "invalid_outcome"}), 400
    owned = db.get_record_owned(user_key, record_id)
    if not owned:
        return jsonify({"ok": False, "error": "not_found"}), 404
    db.save_followup(user_key, record_id, outcome, new_sign)
    return jsonify({
        "ok": True,
        "recorded": True,
        "outcome": outcome,
        "new_sign": new_sign,
        "reanalyze_recommended": outcome in {"same", "worse"} or new_sign,
        "analysis": owned,
    })


