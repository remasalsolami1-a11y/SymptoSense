@route("/api/symptoms/extract", methods=["POST"])
def api_symptoms_extract():
    data=request.get_json(silent=True) or {}
    lang="en" if data.get("lang")=="en" else "ar"
    text=data.get("text", "")
    try:
        result=advanced_features.smart_extract_symptoms(text, lang) or {}
    except Exception:
        logging.getLogger(__name__).warning("Handled exception in api_symptoms_extract; fallback applied (handler 14079)")
        result={}
    found=list(result.get("found") or [])
    seen=set()
    for item in found:
        key=str(item.get("slug") or item.get("name_ar") or item.get("name_en") or "").strip().lower()
        if key: seen.add(key)
    for item in _local_symptom_hits(text):
        key=item["slug"].lower()
        if key not in seen:
            found.append(item); seen.add(key)
    result["found"]=found[:24]
    # Natural-language context is extracted deterministically from the user's own
    # wording. It is used only to avoid repetitive questions and to summarize
    # timing/triggers; it never creates a diagnosis.
    result["context"] = symptom_context.extract_context(text, found=found[:24], lang=lang)
    # Keep unknown free-text symptoms instead of forcing a wrong match.  The
    # client then routes them through a body-system/context clarifier.
    result["lexicon_version"]="symptom-universal-context-v4"
    return jsonify({"ok": True, **result})


