            result["search_intent_v4"] = v2_search.get("query_intent") or "explain"
            result["search_contexts_v4"] = v2_search.get("contexts") or []
            result["did_you_mean_v4"] = v2_search.get("did_you_mean")
            genuinely_combined_count = len([h for h in result["recognized_symptoms_v3"] if _hit_actually_in_query(h)])
