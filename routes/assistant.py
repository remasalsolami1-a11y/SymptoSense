@route("/api/analyze/safety-check", methods=["POST"])
def api_analyze_safety_check():
    """Fast deterministic red-flag check before adaptive follow-up questions.

    This endpoint never diagnoses. It exists only to bypass normal questioning
    when a narrow, high-concern safety rule matches the user's current input.
    """
    try:
        if not _service_consent_ok():
            return _consent_required_json("/chat")
        data = request.get_json(silent=True) or {}
        invalid_field = _analysis_input_error(data)
        if invalid_field:
            return jsonify({"ok": False, "error": "Invalid input.", "error_code": "invalid_input", "field": invalid_field}), 400
        lang = "en" if data.get("lang") == "en" else "ar"
        symptoms = data.get("symptoms") or []
        if isinstance(symptoms, str):
            symptoms = [symptoms]
        patient = {
            "symptoms": [str(x).strip() for x in symptoms if str(x).strip()][:30],
            "notes": _sanitize_analysis_notes_for_safety(data.get("notes")),
            "age": data.get("age"),
            "severity": data.get("severity"),
            "duration": data.get("duration"),
        }
        safety = safety_engine.evaluate(patient, lang=lang)
        payload = {"ok": True, "emergency": bool(safety.get("emergency")), "safety_engine": safety}
        if safety.get("emergency"):
            decision_log.record("emergency", safety.get("rule_ids"), lang, "safety_check")
        if safety.get("emergency"):
            payload["result"] = safety_engine.emergency_result(safety, lang=lang)
        return jsonify(payload)
    except Exception as exc:
        return _mk_error(exc, 500)


