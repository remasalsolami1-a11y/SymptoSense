"""Real Arabic words that typo correction must leave alone (V290).

arabic_lexicon.txt is generated by tools/build_arabic_lexicon.py from the app's own
Arabic content. A token is "real" when it, or the token without a leading و/ف/ب/ل or
ال/وال/بال, is in the list.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

_PATH = Path(__file__).resolve().with_name("arabic_lexicon.txt")
_PREFIXES = ("وال", "بال", "فال", "لل", "ال", "و", "ف", "ب", "ل")


@lru_cache(maxsize=1)
def words() -> frozenset[str]:
    try:
        return frozenset(_PATH.read_text(encoding="utf-8").split())
    except OSError:
        return frozenset()


def is_real_word(token: str) -> bool:
    lex = words()
    if token in lex:
        return True
    for p in _PREFIXES:
        if token.startswith(p) and len(token) - len(p) >= 3 and token[len(p):] in lex:
            return True
    return False
